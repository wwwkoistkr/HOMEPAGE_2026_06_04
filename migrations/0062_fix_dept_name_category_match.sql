-- 증상: '보안기능 시험'/'암호모듈 검증시험' 시험현황 페이지가
--       데이터가 있는데도 "등록된 현황이 없습니다(총 0건)"로 표시됨
-- 원인: 코드가 category = departments.name 으로 조회하는데,
--       부서명(공백 有)과 데이터 category(공백 無)가 달라 매칭 실패
--         부서명 '보안기능 시험'(7자)  ≠  데이터 '보안기능시험'(6자)
--         부서명 '암호모듈 검증시험'(9자) ≠ 데이터 '암호모듈검증'(6자)
-- 조치(방법 A): 부서명을 데이터 category와 동일하게 통일
--               (운영 koist.ai.kr 와 동일한 상태로 정렬)
-- 생성일: 2026-06-30
-- ============================================================

UPDATE departments SET name = '보안기능시험' WHERE slug = 'security-test' AND name <> '보안기능시험';
UPDATE departments SET name = '암호모듈검증' WHERE slug = 'kcmvp' AND name <> '암호모듈검증';
